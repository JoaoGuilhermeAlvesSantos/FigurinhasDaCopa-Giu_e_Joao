(function () {
  "use strict";

  const PASSWORD = "giucabeçinha";
  const $ = (selector, ctx = document) => ctx.querySelector(selector);
  const CODE_PATTERN = /\b([A-Z]{2,3}\d{1,2})\b/g;

  function normalizeCode(code) {
    return String(code).trim().replace(/\s+/g, "").toUpperCase();
  }

  function sortStickerCodes(codes) {
    return [...codes].sort((a, b) => {
      const matchA = a.match(/^([A-Z]+)(\d+)$/);
      const matchB = b.match(/^([A-Z]+)(\d+)$/);
      if (!matchA || !matchB) return a.localeCompare(b);
      if (matchA[1] !== matchB[1]) return matchA[1].localeCompare(matchB[1]);
      return Number(matchA[2]) - Number(matchB[2]);
    });
  }

  function parseInput(rawText) {
    const results = new Set();
    const lines = rawText.split(/\r?\n/);
    for (const line of lines) {
      const matches = [...line.matchAll(CODE_PATTERN)];
      for (const match of matches) {
        results.add(normalizeCode(match[1]));
      }
    }
    return [...results];
  }

  function buildTeamIndex() {
    return ALBUM_DATA.teams.reduce((acc, team) => {
      acc[team.code] = team;
      return acc;
    }, {});
  }

  function getTeamPrefix(code) {
    const match = code.match(/^[A-Z]{2,3}/);
    return match ? match[0] : null;
  }

  function buildGroups(teams) {
    const groups = {};
    for (const team of teams) {
      if (team.group === "–") continue;
      if (!groups[team.group]) {
        groups[team.group] = { letter: team.group, total: 0, collected: 0, teams: [] };
      }
      groups[team.group].total += team.total;
      groups[team.group].collected += team.collected;
      groups[team.group].teams.push(team.code);
    }
    return Object.values(groups).map((group) => ({
      ...group,
      percent: group.total ? Number(((group.collected / group.total) * 100).toFixed(1)) : 0,
    }));
  }

  function countCompleteTeams(teams) {
    return teams.filter((team) => team.group !== "–" && team.percent === 100).length;
  }

  function buildUpdatedData(foundCodes) {
    const teamIndex = buildTeamIndex();
    const teams = ALBUM_DATA.teams.map((team) => {
      const missing = [...(team.missing || [])].filter((sticker) => {
        return !foundCodes.includes(normalizeCode(sticker));
      });
      const collected = team.total - missing.length;
      return {
        ...team,
        collected,
        percent: team.total ? Number(((collected / team.total) * 100).toFixed(1)) : 0,
        missing: sortStickerCodes(missing),
      };
    });

    const totalCollected = teams.reduce((sum, team) => sum + team.collected, 0);
    const totalMissing = teams.reduce((sum, team) => sum + (team.missing || []).length, 0);
    const totalStickers = teams.reduce((sum, team) => sum + team.total, 0);

    return {
      ...ALBUM_DATA,
      meta: {
        ...ALBUM_DATA.meta,
        collected: totalCollected,
        missing: totalMissing,
        percent: totalStickers ? Number(((totalCollected / totalStickers) * 100).toFixed(1)) : 0,
        completeTeams: countCompleteTeams(teams),
        updated: new Date().toISOString().slice(0, 10),
      },
      teams,
      groups: buildGroups(teams),
      special: teams.filter((team) => team.group === "–"),
    };
  }

  function createDataJsText(updatedData) {
    return `// Auto-generated by ingest.js – ${new Date().toISOString().slice(0, 10)}\n` +
      `const ALBUM_DATA = ${JSON.stringify(updatedData, null, 2)};\n`;
  }

  function showStatus(message, isError = false) {
    const status = $("#ingest-status");
    if (!status) return;
    status.textContent = message;
    status.style.color = isError ? "var(--danger)" : "var(--text)";
    if (!isError) {
      setTimeout(() => { status.textContent = ""; }, 4000);
    }
  }

  function updateSummary(summaryText) {
    const summary = $("#ingest-summary");
    if (summary) summary.textContent = summaryText;
  }

  function copyToClipboard(text) {
    navigator.clipboard.writeText(text).then(() => {
      showStatus("Conteúdo copiado para a área de transferência.");
    });
  }

  async function saveDataJsFile(text) {
    if (typeof window.showSaveFilePicker !== "function") {
      showStatus("Gravação direta não suportada neste navegador. Use Baixar data.js.", true);
      return;
    }

    try {
      const handle = await window.showSaveFilePicker({
        suggestedName: "data.js",
        types: [
          {
            description: "JavaScript",
            accept: { "application/javascript": [".js"] },
          },
        ],
      });
      const writable = await handle.createWritable();
      await writable.write(text);
      await writable.close();
      showStatus("data.js atualizado com sucesso.");
    } catch (err) {
      if (err.name !== "AbortError") {
        showStatus(`Falha ao salvar: ${err.message}`, true);
      }
    }
  }

  function downloadDataJs(text) {
    const blob = new Blob([text], { type: "application/javascript;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement("a");
    anchor.href = url;
    anchor.download = "data.js";
    document.body.appendChild(anchor);
    anchor.click();
    anchor.remove();
    URL.revokeObjectURL(url);
  }

  function renderOutput(foundCodes) {
    const output = $("#ingest-output");
    if (!output) return;
    if (!foundCodes.length) {
      output.value = "";
      updateSummary("Nenhum código válido encontrado. Cole a lista e clique em Processar input.");
      return;
    }

    const updatedData = buildUpdatedData(foundCodes);
    output.value = createDataJsText(updatedData);
    updateSummary(`Gerado data.js com ${foundCodes.length} código(s) processado(s).`);
  }

  function processInput() {
    const rawText = $("#ingest-input").value || "";
    const foundCodes = parseInput(rawText);
    if (!foundCodes.length) {
      showStatus("Nenhum código de figurinha válido encontrado.", true);
      renderOutput([]);
      return;
    }

    renderOutput(foundCodes);
    showStatus(`Processado ${foundCodes.length} código(s).`);
  }

  function attachEvents() {
    const passwordField = $("#ingest-password");
    const passwordSubmit = $("#ingest-password-submit");
    const processButton = $("#ingest-process");
    const copyButton = $("#ingest-copy-js");
    const downloadButton = $("#ingest-download-js");
    const resetButton = $("#ingest-reset");

    if (passwordSubmit) {
      passwordSubmit.addEventListener("click", () => {
        if (passwordField.value === PASSWORD) {
          $("#password-overlay").classList.add("hidden");
          $("#ingest-page").classList.remove("hidden");
          passwordField.value = "";
          showStatus("Acesso autorizado.");
        } else {
          const error = $("#password-error");
          if (error) {
            error.textContent = "Senha incorreta. Tente novamente.";
          }
        }
      });
    }

    if (processButton) {
      processButton.addEventListener("click", processInput);
    }

    if (copyButton) {
      copyButton.addEventListener("click", () => {
        const output = $("#ingest-output");
        if (output && output.value) {
          copyToClipboard(output.value);
        } else {
          showStatus("Nada para copiar. Primeiro processe o input.", true);
        }
      });
    }

    if (downloadButton) {
      downloadButton.addEventListener("click", () => {
        const output = $("#ingest-output");
        if (output && output.value) {
          downloadDataJs(output.value);
        } else {
          showStatus("Nada para baixar. Primeiro processe o input.", true);
        }
      });
    }

    const saveButton = $("#ingest-save-js");
    if (saveButton) {
      saveButton.addEventListener("click", async () => {
        const output = $("#ingest-output");
        if (output && output.value) {
          await saveDataJsFile(output.value);
        } else {
          showStatus("Nada para salvar. Primeiro processe o input.", true);
        }
      });
    }

    if (resetButton) {
      resetButton.addEventListener("click", () => {
        $("#ingest-input").value = "";
        $("#ingest-output").value = "";
        updateSummary("Ainda não processado.");
        showStatus("Campos limpos.");
      });
    }
  }

  function init() {
    if (typeof ALBUM_DATA === "undefined") {
      document.body.innerHTML = `<p style="padding:2rem;color:red">Erro: data.js não encontrado. Execute generate_site_data.py primeiro.</p>`;
      return;
    }

    attachEvents();
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
